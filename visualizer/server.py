class OrganismController:
    """Orchestrates the background cognitive organism simulation and maintains sensory/cognitive telemetries."""

    def __init__(self, seed: int = 42, sleep_every: int = 400):
        self.lock = threading.Lock()
        self.seed = seed
        self.sleep_every = sleep_every
        self.env = MockWeb(n_pages=30, seed=seed)
        self.org = Organism(self.env, seed=seed, sleep_every=sleep_every, autosave_every=0, verbose=False)
        self.running = True
        self.paused = False
        self.delay = 0.15           # step delay in seconds
        self.single_step_flag = False

        # History queues for Speaking and Listening
        self.spoken_history: deque = deque(maxlen=25)
        self.listening_history: deque = deque(maxlen=25)
        self.latest_spoken: str = "Awaiting initial thought synthesis..."
        self.latest_heard: str = "(No external speech received yet)"

        self.latest_telemetry: Dict[str, Any] = {}
        self.fps = 0.0
        self.sse_queues: List[queue.Queue] = []

        self._thread = threading.Thread(target=self._run_loop, daemon=True)
        self._thread.start()

    def register_client(self) -> queue.Queue:
        q: queue.Queue = queue.Queue(maxsize=15)
        with self.lock:
            self.sse_queues.append(q)
        return q

    def unregister_client(self, q: queue.Queue):
        with self.lock:
            if q in self.sse_queues:
                self.sse_queues.remove(q)

    def _broadcast(self, data: Dict[str, Any]):
        msg = f"data: {json.dumps(data)}\n\n"
        with self.lock:
            dead = []
            for q in self.sse_queues:
                try:
                    q.put_nowait(msg)
                except queue.Full:
                    try:
                        q.get_nowait()
                        q.put_nowait(msg)
                    except Exception:
                        pass
                except Exception:
                    dead.append(q)
            for d in dead:
                if d in self.sse_queues:
                    self.sse_queues.remove(d)

    def _encode_rgb_thumbnail(self, rgb: np.ndarray) -> str:
        im_arr = np.clip(rgb * 255.0, 0, 255).astype(np.uint8)
        img = Image.fromarray(im_arr)
        buf = io.BytesIO()
        img.save(buf, format="PNG")
        b64 = base64.b64encode(buf.getvalue()).decode("ascii")
        return f"data:image/png;base64,{b64}"

    def _extract_telemetry(self, rec: Dict[str, Any]) -> Dict[str, Any]:
        """Assembles structured telemetry highlighting Seeing, Thinking, Speaking, and Listening."""
        org = self.org
        env = self.env
        now_ts = time.strftime("%H:%M:%S")

        # 1. SEEING: Retinal vision & page content
        rendered_rgb = env._render()
        b64_image = self._encode_rgb_thumbnail(rendered_rgb)
        is_click = rec["a"] < N_CELLS
        fix_col = (rec["a"] % CELL_COLS) if is_click else None
        fix_row = (rec["a"] // CELL_COLS) if is_click else None
        page_text = env.pages[env.cur]["text"] if hasattr(env, "pages") else ""

        seeing = {
            "image": b64_image,
            "scene_text": page_text,
            "page_id": env.cur,
            "total_pages": env.n_pages,
            "pages_visited": len(env.visited),
            "effective_clicks": env.effective,
            "total_clicks": env.clicks,
            "action": {
                "id": rec["a"],
                "name": action_name(rec["a"]),
                "info": str(rec.get("info", "")),
                "is_click": is_click,
                "col": fix_col,
                "row": fix_row,
            },
            "novelty": round(float(rec.get("nov", 0.0)), 3),
            "change": round(float(rec.get("change", 0.0)), 3),
        }

        # Check for any new spoken responses from organism
        while not org.replies.empty():
            try:
                rep = org.replies.get_nowait().strip()
                if rep:
                    self.latest_spoken = rep
                    self.spoken_history.append({"time": now_ts, "text": rep})
            except Exception:
                break

        # If thought is active, keep speaking updated
        current_thought = rec.get("thought", "")
        if current_thought and len(self.spoken_history) == 0:
            self.latest_spoken = current_thought

        # 2. THINKING: Inner monologue, workspace, concepts, drives & metacognition
        ws_items = []
        for it in org.ws.items:
            ws_items.append({
                "src": it["src"],
                "words": it["words"],
                "salience": round(float(it["sal"]), 3),
            })

        active_idx = org.prev["state"][0].tolist() if org.prev else []
        thinking = {
            "current_thought": current_thought or "Synthesizing associations...",
            "active_concepts": org.last_concepts,
            "workspace_items": ws_items,
            "curiosity": round(float(org.drives.curiosity), 3),
            "boredom": round(float(org.drives.boredom), 3),
            "fatigue": round(float(org.drives.fatigue), 3),
            "social_drive": round(float(org.drives.social), 3),
            "confidence": round(float(org.me.confidence), 3),
            "forward_error": round(float(org.fwd.fast), 4),
            "learning_progress": round(float(org.fwd.progress), 4),
            "td_delta": round(float(rec.get("delta", 0.0)), 3),
            "reward": round(float(rec.get("r", 0.0)), 3),
            "cortical_active_units": active_idx,
            "engrams_count": org.mem.n,
            "engrams_capacity": org.mem.cap,
        }

        # 3. SPEAKING: Vocal utterances and vocabulary
        speaking = {
            "last_spoken": self.latest_spoken,
            "history": list(self.spoken_history),
            "vocabulary_size": len(org.lang.w2i),
        }

        # 4. LISTENING: Auditory inputs received
        listening = {
            "last_heard": self.latest_heard,
            "history": list(self.listening_history),
            "is_active": True,
        }

        # 5. HYPERPARAMETERS: Current configurable parameters
        hyperparameters = {
            "k_sparsity": org.encoder.k,
            "encoder_eta": round(float(org.encoder.eta), 4),
            "policy_eta": round(float(org.policy.eta), 3),
            "policy_gamma": round(float(org.policy.gamma), 3),
            "policy_lam": round(float(org.policy.lam), 3),
            "memory_alloc": round(float(org.mem.alloc), 3),
            "sleep_every": org.drives.sleep_every,
            "step_delay_ms": round(self.delay * 1000),
        }

        return {
            "step": org.t,
            "running": self.running and not self.paused,
            "fps": round(self.fps, 1),
            "seeing": seeing,
            "thinking": thinking,
            "speaking": speaking,
            "listening": listening,
            "hyperparameters": hyperparameters,
            "stats": org.me.report(),
        }

    def _run_loop(self):
        fps_count = 0
        fps_timer = time.time()

        while self.running:
            should_step = (not self.paused) or self.single_step_flag
            if should_step:
                self.single_step_flag = False
                t0 = time.time()
                try:
                    rec = self.org.step()
                    if self.org.drives.fatigue >= 1.0:
                        self.org.sleep()
                    telemetry = self._extract_telemetry(rec)
                    self.latest_telemetry = telemetry
                    self._broadcast(telemetry)
                    fps_count += 1
                except Exception as e:
                    print(f"[Visualizer] Step error: {e}")

                if time.time() - fps_timer >= 1.0:
                    self.fps = fps_count / (time.time() - fps_timer)
                    fps_count = 0
                    fps_timer = time.time()

                dur = time.time() - t0
                time.sleep(max(0.01, self.delay - dur))
            else:
                time.sleep(0.05)

    def speak_to_organism(self, text: str) -> Dict[str, Any]:
        """Delivers human speech input directly into the organism's auditory channel."""
        clean_text = text.strip()
        if not clean_text:
            return {"status": "ignored", "reason": "empty text"}
        now_ts = time.strftime("%H:%M:%S")
        with self.lock:
            self.latest_heard = clean_text
            self.listening_history.append({"time": now_ts, "text": clean_text})
            self.org.hear(clean_text)
        return {"status": "success", "heard": clean_text}

    def update_hyperparameters(self, params: Dict[str, Any]) -> Dict[str, Any]:
        applied = {}
        with self.lock:
            org = self.org
            if "k_sparsity" in params or "encoder_k" in params:
                val = int(params.get("k_sparsity", params.get("encoder_k")))
                org.encoder.k = max(1, min(128, val))
                applied["k_sparsity"] = org.encoder.k
            if "encoder_eta" in params:
                org.encoder.eta = float(params["encoder_eta"])
                applied["encoder_eta"] = org.encoder.eta
            if "policy_eta" in params:
                org.policy.eta = float(params["policy_eta"])
                applied["policy_eta"] = org.policy.eta
            if "policy_gamma" in params:
                org.policy.gamma = max(0.1, min(0.999, float(params["policy_gamma"])))
                applied["policy_gamma"] = org.policy.gamma
            if "policy_lam" in params:
                org.policy.lam = max(0.0, min(0.99, float(params["policy_lam"])))
                applied["policy_lam"] = org.policy.lam
            if "memory_alloc" in params:
                org.mem.alloc = max(0.05, min(0.9, float(params["memory_alloc"])))
                applied["memory_alloc"] = org.mem.alloc
            if "sleep_every" in params:
                org.drives.sleep_every = max(50, int(params["sleep_every"]))
                applied["sleep_every"] = org.drives.sleep_every
            if "step_delay_ms" in params or "delay" in params:
                val = float(params.get("step_delay_ms", 0)) / 1000.0 if "step_delay_ms" in params else float(params["delay"])
                self.delay = max(0.005, min(2.0, val))
                applied["step_delay_ms"] = round(self.delay * 1000)
            if self.latest_telemetry and "hyperparameters" in self.latest_telemetry:
                self.latest_telemetry["hyperparameters"].update(applied)
        return applied

    def handle_control(self, action: str, value: Any = None) -> Dict[str, Any]:
        with self.lock:
            if action == "pause":
                self.paused = True
                return {"paused": True}
            elif action == "resume":
                self.paused = False
                return {"paused": False}
            elif action == "step":
                self.paused = True
                self.single_step_flag = True
                return {"stepped": True}
            elif action == "sleep":
                self.org.sleep()
                return {"slept": True}
            elif action == "reward":
                self.org.feedback(+1.0)
                return {"feedback": +1.0}
            elif action == "punish":
                self.org.feedback(-1.0)
                return {"feedback": -1.0}
            elif action == "reset":
                seed = int(value) if value is not None else 42
                self.env = MockWeb(n_pages=30, seed=seed)
                self.org = Organism(self.env, seed=seed, sleep_every=self.sleep_every, autosave_every=0, verbose=False)
                self.spoken_history.clear()
                self.listening_history.clear()
                self.latest_spoken = "Reset complete. Synthesizing new experience..."
                self.latest_heard = "(Awaiting input after reset)"
                return {"reset": True, "seed": seed}
        return {"error": f"Unknown action: {action}"}


class VisualizerHTTPHandler(SimpleHTTPRequestHandler):
    """Clean HTTP Handler serving REST endpoints and static files."""

    controller: OrganismController

    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=STATIC_DIR, **kwargs)

    def log_message(self, format: str, *args):
        # Mute routine telemetry polls to avoid cluttering stdout
        try:
            msg = format % args
            if "/api/telemetry" in msg or "/api/stream" in msg:
                return
        except Exception:
            pass
        super().log_message(format, *args)

    def do_GET(self):
        url = urlparse(self.path)

        if url.path == "/api/telemetry":
            # Primary JSON polling endpoint
            self.send_response(HTTPStatus.OK)
            self.send_header("Content-Type", "application/json")
            self.send_header("Cache-Control", "no-cache")
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()
            self.wfile.write(json.dumps(self.controller.latest_telemetry).encode("utf-8"))
            return

        elif url.path == "/api/stream":
            # Real-time SSE push stream
            self.send_response(HTTPStatus.OK)
            self.send_header("Content-Type", "text/event-stream")
            self.send_header("Cache-Control", "no-cache")
            self.send_header("Connection", "keep-alive")
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()

            client_q = self.controller.register_client()
            try:
                if self.controller.latest_telemetry:
                    init_msg = f"data: {json.dumps(self.controller.latest_telemetry)}\n\n"
                    self.wfile.write(init_msg.encode("utf-8"))
                    self.wfile.flush()
                while True:
                    msg = client_q.get()
                    self.wfile.write(msg.encode("utf-8"))
                    self.wfile.flush()
            except (BrokenPipeError, ConnectionResetError):
                pass
            finally:
                self.controller.unregister_client(client_q)
            return

        elif url.path in ("/", ""):
            self.path = "/index.html"

        elif url.path == "/favicon.ico":
            self.send_response(HTTPStatus.NO_CONTENT)
            self.end_headers()
            return

        return super().do_GET()

    def do_POST(self):
        url = urlparse(self.path)
        content_len = int(self.headers.get("Content-Length", 0))
        body = self.rfile.read(content_len).decode("utf-8") if content_len > 0 else "{}"
        try:
            payload = json.loads(body)
        except Exception:
            payload = {}

        response_data: Dict[str, Any] = {}

        if url.path in ("/api/listen", "/api/speak", "/api/talk"):
            # Human speaking -> Model listening
            text = payload.get("text", payload.get("message", ""))
            response_data = self.controller.speak_to_organism(text)

        elif url.path == "/api/hyperparameters":
            # Live tuning
            response_data = self.controller.update_hyperparameters(payload)

        elif url.path == "/api/control":
            # Executive action (pause, resume, step, reward, punish, sleep, reset)
            action = payload.get("action", payload.get("command", ""))
            val = payload.get("value")
            response_data = self.controller.handle_control(action, val)

        else:
            self.send_error(HTTPStatus.NOT_FOUND, f"Unknown API endpoint: {url.path}")
            return

        self.send_response(HTTPStatus.OK)
        self.send_header("Content-Type", "application/json")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.end_headers()
        self.wfile.write(json.dumps(response_data).encode("utf-8"))


def find_free_port(preferred_port: int, max_attempts: int = 20) -> int:
    for p in range(preferred_port, preferred_port + max_attempts):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            if s.connect_ex(("127.0.0.1", p)) != 0:
                return p
    return preferred_port


def run_server(host: str = "127.0.0.1", port: int = 8080, seed: int = 42):
    free_port = find_free_port(port)
    controller = OrganismController(seed=seed)
    VisualizerHTTPHandler.controller = controller

    server = ThreadingHTTPServer((host, free_port), VisualizerHTTPHandler)
    url = f"http://{host}:{free_port}/"
    print("=" * 80)
    print("  🧠 ORGANISM COGNITIVE WEB VISUALIZER RUNNING")
    print(f"  👉 Dashboard: {url}")
    print(f"  📡 Telemetry API: http://{host}:{free_port}/api/telemetry")
    print(f"  👂 Listen/Intercom API: http://{host}:{free_port}/api/listen")
    print(f"  ⚙️  Hyperparameter API: http://{host}:{free_port}/api/hyperparameters")
    print("=" * 80)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStopping visualizer server...")
    finally:
        controller.running = False
        server.server_close()


